"""Rasterize a TTF into fixed-cell 1bpp fonts for the beltpack display.
Usage: python3 genfont.py <font.ttf> > ../main/fonts.h
Each glyph is stored column-major: for cell width W and height H, W*ceil(H/8)
bytes, byte k of column x holds rows 8k..8k+7 (LSB = top), the native
layout of SSD1306/SH1106 pages."""
import sys
from PIL import Image, ImageDraw, ImageFont

def gen(path, name, cw, ch, size, yoff):
    font = ImageFont.truetype(path, size)
    pages = (ch + 7) // 8
    out = []
    for c in range(32, 127):
        img = Image.new("L", (cw, ch), 0)
        d = ImageDraw.Draw(img)
        bbox = font.getbbox(chr(c))
        x = (cw - (bbox[2] - bbox[0])) // 2 - bbox[0]
        d.text((x, yoff), chr(c), font=font, fill=255)
        px = img.load()
        cols = []
        for gx in range(cw):
            for p in range(pages):
                b = 0
                for bit in range(8):
                    y = p * 8 + bit
                    if y < ch and px[gx, y] > 110:
                        b |= 1 << bit
                cols.append(b)
        out.append(cols)
    lines = [f"// {name}: {cw}x{ch}, ASCII 32..126, generated by tools/genfont.py",
             f"static const uint8_t {name}[95][{cw * pages}] = {{"]
    for i, cols in enumerate(out):
        lines.append("  {" + ",".join(f"0x{b:02x}" for b in cols) + f"}}, // '{chr(32 + i) if chr(32 + i) not in '\\\\' else 'bs'}'")
    lines.append("};")
    return "\n".join(lines), out

def preview(glyphs, cw, ch, fn):
    pages = (ch + 7) // 8
    img = Image.new("L", (cw * 32, ch * 3), 0)
    for i, cols in enumerate(glyphs):
        ox, oy = (i % 32) * cw, (i // 32) * ch
        for gx in range(cw):
            for p in range(pages):
                b = cols[gx * pages + p]
                for bit in range(8):
                    if b >> bit & 1 and p * 8 + bit < ch:
                        img.putpixel((ox + gx, oy + p * 8 + bit), 255)
    img.resize((img.width * 4, img.height * 4), Image.NEAREST).save(fn)

if __name__ == "__main__":
    ttf = sys.argv[1]
    s1, g1 = gen(ttf, "font_small", 6, 8, 8, -1)
    s2, g2 = gen(ttf, "font_big", 8, 16, 14, -1)
    if len(sys.argv) > 2:
        preview(g1, 6, 8, sys.argv[2] + "_small.png")
        preview(g2, 8, 16, sys.argv[2] + "_big.png")
    print("#pragma once\n#include <stdint.h>\n")
    print(s1)
    print()
    print(s2)
